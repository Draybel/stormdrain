/**
 * The six unlockable characters (DESIGN.md "Characters"): Pip, Marrow, Juniper, Bolt, Sable, Mosswick.
 * Every character sprite follows Wren's 14×16 frame layout (`WREN_FRAME`, content/sprites/wren.ts) so the
 * world renderer, the character select, the pause menu and the ending screen draw any of them the same way:
 *   0 down, 1-2 down steps, 3 down blink, 4 up, 5-6 up steps, 7-8 side (right; mirrored for left),
 *   9 hurt, 10 death slump, 11 death heap.
 * A body is 14 rows; the feet (2 rows) are added per frame, like Wren's boots. All art is original.
 */

import type { SpriteDef } from '../../sim/types';
import { OUTLINE } from './palette';

/** Two rows of feet per walk pose. */
export interface FeetSet {
  stand: readonly string[];
  left: readonly string[];
  right: readonly string[];
  sideTogether: readonly string[];
  sideSpread: readonly string[];
}

export interface CharacterArt {
  id: string;
  palette: Readonly<Record<string, string>>;
  /** 14-row bodies. */
  down: readonly string[];
  blink: readonly string[];
  hurt: readonly string[];
  up: readonly string[];
  side: readonly string[];
  feet: FeetSet;
  /** Full 16-row death frames. */
  slump: readonly string[];
  heap: readonly string[];
}

/** Builds a character SpriteDef in Wren's frame layout (see WREN_FRAME). */
export function characterSprite(a: CharacterArt): SpriteDef {
  const f = a.feet;
  return {
    id: a.id,
    w: 14,
    h: 16,
    anchorX: 7,
    anchorY: 15,
    palette: a.palette,
    frames: [
      [...a.down, ...f.stand],
      [...a.down, ...f.left],
      [...a.down, ...f.right],
      [...a.blink, ...f.stand],
      [...a.up, ...f.stand],
      [...a.up, ...f.left],
      [...a.up, ...f.right],
      [...a.side, ...f.sideTogether],
      [...a.side, ...f.sideSpread],
      [...a.hurt, ...f.stand],
      a.slump,
      a.heap,
    ],
    anims: {
      idleDown: { frames: [0], fps: 1, loop: true },
      walkDown: { frames: [1, 0, 2, 0], fps: 8, loop: true },
      idleUp: { frames: [4], fps: 1, loop: true },
      walkUp: { frames: [5, 4, 6, 4], fps: 8, loop: true },
      idleSide: { frames: [7], fps: 1, loop: true },
      walkSide: { frames: [8, 7, 8, 7], fps: 8, loop: true },
      hurt: { frames: [9], fps: 1, loop: false },
      death: { frames: [9, 10, 11], fps: 6, loop: false },
    },
  };
}

/** Replaces row `i` of `rows` (a copy). */
function edit(rows: readonly string[], changes: Readonly<Record<number, string>>): string[] {
  return rows.map((r, i) => changes[i] ?? r);
}

