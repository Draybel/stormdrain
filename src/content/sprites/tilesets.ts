/**
 * Chapter tilesets: floor and wall PATTERNS as pixel maps with palette letters, recoloured per
 * chapter by render/chapterArt.ts (ChapterDef.palette). A chapter picks one floor pattern and one wall
 * pattern: `ChapterDef.tileset = '<floor>/<wall>'` (e.g. 'checker/panel').
 *
 * Floor pattern letters: a floor, b floorLight, c floorDark, m mortar, g moss, G mossLight,
 * i stoneShade, I stone, k deep. Five frames each, same meaning in every pattern:
 * 0 plain, 1 alternate, 2 cracked / detailed, 3 edge feature (moss, frost, wax… in the moss colours),
 * 4 rare feature (a grate, a vent, a rune).
 * Wall pattern letters (authored for the TOP wall, floor side at the bottom row): k deep, m mortar,
 * W brick, w brickShade, L brickLight, g moss, G mossLight. Two frames: plain, variant.
 * Some patterns are generated by code (deterministic), the gutter ones are the Phase 1 art.
 */

import { FLOOR_SPRITE, WALL_SPRITE } from './gutterways';

export type PatternFrames = readonly (readonly string[])[];

const N = 16;

/** Builds a 16×16 frame from a per-pixel function. */
function frame(fn: (x: number, y: number) => string): string[] {
  const rows: string[] = [];
  for (let y = 0; y < N; y++) {
    let r = '';
    for (let x = 0; x < N; x++) r += fn(x, y);
    rows.push(r);
  }
  return rows;
}

/** Deterministic 0..1 hash of a pixel (+ salt) for speckles. */
function h(x: number, y: number, salt: number): number {
  let v = (x * 374761393 + y * 668265263 + salt * 2147483647) | 0;
  v = Math.imul(v ^ (v >>> 13), 1274126177);
  v ^= v >>> 16;
  return (v >>> 0) / 4294967296;
}

/** Overlays the pixels of `over` ('.' = keep) onto `base`. */
function stamp(base: string[], over: readonly string[], ox = 0, oy = 0): string[] {
  const out = base.slice();
  for (let y = 0; y < over.length; y++) {
    const ty = y + oy;
    if (ty < 0 || ty >= N) continue;
    const row = out[ty]!.split('');
    const o = over[y]!;
    for (let x = 0; x < o.length; x++) {
      const tx = x + ox;
      if (tx >= 0 && tx < N && o[x] !== '.') row[tx] = o[x]!;
    }
    out[ty] = row.join('');
  }
  return out;
}

const MOSS_CORNER = ['g...', 'Gg..', 'gGg.', 'GggG', 'ggGg'];
const GRATE = ['IIIIIIII', 'IkIkIkIk', 'IkIkIkIk', 'IkIkIkIk', 'IkIkIkIk', 'iiiiiiii'];
const CRACK = ['..m.....', '...m....', '...m....', '..m.m...', '.m...m..', '.m....m.'];

// ── Floor patterns ───────────────────────────────────────────────────────────

/** Nursery tiles: a 2×2 checker of 8 px tiles with grout. */
function checker(v: number): string[] {
  const base = frame((x, y) => {
    if (x % 8 === 7 || y % 8 === 7) return 'm';
    const dark = ((x >> 3) + (y >> 3)) & 1;
    if (x % 8 === 0 || y % 8 === 0) return dark ? 'a' : 'b';
    return dark ? 'c' : 'a';
  });
  if (v === 1) return stamp(base, ['m', 'mm', 'mmm'], 0, 0); // a chipped corner
  if (v === 2) return stamp(base, CRACK, 4, 5);
  if (v === 3) return stamp(base, MOSS_CORNER, 0, 11);
  if (v === 4) return stamp(base, GRATE, 4, 5);
  return base;
}

/** Packed earth with pebbles. */
function earth(v: number): string[] {
  const base = frame((x, y) => {
    const r = h(x, y, v === 1 ? 7 : 3);
    if (r < 0.05) return 'c';
    if (r < 0.08) return 'b';
    if (r > 0.985) return 'I';
    if (r > 0.97) return 'i';
    return 'a';
  });
  if (v === 2) return stamp(base, ['.....m', '....m.', 'mmmm..', 'm.....', '.m....'], 4, 6);
  if (v === 3) return stamp(base, ['.g.G..', 'gGgGg.', '.GgGgG', 'g.gg.g'], 1, 11);
  if (v === 4) return stamp(base, ['.iii.', 'iIIIi', 'iIIIi', '.iii.'], 5, 6); // a buried stone
  return base;
}

/** Big bevelled slabs (crypts, grottos, vaults). */
function slab(v: number): string[] {
  const base = frame((x, y) => {
    if (x === 15 || y === 15) return 'm';
    if (x === 0 || y === 0) return 'b';
    if (x === 14 || y === 14) return 'c';
    if (v === 1 && h(x, y, 11) < 0.04) return 'b';
    return 'a';
  });
  if (v === 2) return stamp(base, ['m.......', '.m......', '.mm.....', '...m....', '...m.m..', '....m.m.', '.......m'], 3, 3);
  if (v === 3) return stamp(base, ['G.........', 'gG.......', 'ggGg.....', 'gGggGg...', 'ggGggggG.'], 1, 9);
  if (v === 4) return stamp(base, ['.III.', 'I...I', 'I.I.I', 'I...I', '.III.'], 5, 5); // a carved ring
  return base;
}

/** Riveted metal plates (works, foundry). */
function plate(v: number): string[] {
  const base = frame((x, y) => {
    if (x === 15 || y === 15) return 'm';
    if ((x === 2 || x === 12) && (y === 2 || y === 12)) return 'I';
    if ((x === 3 || x === 13) && (y === 3 || y === 13)) return 'i';
    if (x === 0 || y === 0) return 'b';
    if (x === 14 || y === 14) return 'c';
    if (v === 1 && (x + y) % 5 === 0 && x > 3 && x < 12 && y > 3 && y < 12) return 'c';
    return 'a';
  });
  if (v === 2) return stamp(base, ['..c..', '.cmc.', 'cm.mc', '.cmc.'], 6, 6); // a dent
  if (v === 3) return stamp(base, ['.gg..', 'gGgg.', 'gggGg', '.ggg.'], 1, 10); // rust / oil
  if (v === 4) return stamp(base, ['kkkkkkkk', 'IIIIIIII', 'kkkkkkkk', 'IIIIIIII', 'kkkkkkkk', 'iiiiiiii'], 4, 5); // a vent
  return base;
}

/** Wasp-paper cells: offset rows of cut-corner cells (tiles seamlessly at 16 px). */
function hex(v: number): string[] {
  const base = frame((x, y) => {
    const row = y >> 3;
    const lx = (x + (row & 1) * 4) % 8;
    const ly = y % 8;
    if (ly === 7 || lx === 7) return 'm';
    if ((lx === 0 || lx === 6) && (ly === 0 || ly === 6)) return 'm';
    if (ly === 0 || lx === 0) return 'b';
    if (ly === 6 || lx === 6) return 'c';
    return 'a';
  });
  if (v === 1) return stamp(base, ['kk', 'kk'], 2, 2); // an empty cell
  if (v === 2) return stamp(base, CRACK, 5, 6);
  if (v === 3) return stamp(base, ['.GG.', 'GggG', 'gggg', '.gg.'], 1, 10); // an amber plug
  if (v === 4) return stamp(base, ['.GGG.', 'GgGgG', 'GgggG', '.GgG.'], 5, 5);
  return base;
}

function five(fn: (v: number) => string[]): PatternFrames {
  return [fn(0), fn(1), fn(2), fn(3), fn(4)];
}

export const FLOOR_PATTERNS: Readonly<Record<string, PatternFrames>> = {
  flagstone: FLOOR_SPRITE.frames,
  checker: five(checker),
  earth: five(earth),
  slab: five(slab),
  plate: five(plate),
  hex: five(hex),
};

// ── Wall patterns (top wall; the floor side is the bottom row) ────────────────

/** Big dressed blocks, two courses. */
function blocks(v: number): string[] {
  const base = frame((x, y) => {
    if (y < 2) return 'k';
    if (y === 2 || y === 9 || y === 15) return 'm';
    const course = y < 9 ? 0 : 1;
    const joint = course === 0 ? 5 : 11;
    if (x === joint) return 'm';
    if (y === 3 || y === 10) return 'L';
    if (y === 8 || y === 14) return 'w';
    return 'W';
  });
  if (v === 1) return stamp(base, ['..g.', '.gGg', 'gGgG', '.g.g'], 9, 11);
  return base;
}

/** Vertical timber boards with nails and a beam on top. */
function timber(v: number): string[] {
  const base = frame((x, y) => {
    if (y < 2) return 'k';
    if (y === 2 || y === 15) return 'm';
    if (y < 6) return y === 3 ? 'L' : y === 5 ? 'w' : 'W';
    if (x % 4 === 3) return 'm';
    if (x % 4 === 0) return 'L';
    if (y === 7 && x % 4 === 1) return 'k';
    return x % 4 === 2 ? 'w' : 'W';
  });
  if (v === 1) return stamp(base, ['.g....', 'gG.g..', '.gGgG.', '..g.gg', '...g..'], 3, 9); // roots poking through
  return base;
}

/** Faded wallpaper stripes over a wainscot rail. */
function panel(v: number): string[] {
  const base = frame((x, y) => {
    if (y < 2) return 'k';
    if (y === 2) return 'm';
    if (y === 11) return 'L';
    if (y === 12) return 'W';
    if (y >= 13) return y === 15 ? 'm' : 'w';
    return (x >> 1) % 3 === 0 ? 'L' : (x >> 1) % 3 === 1 ? 'W' : 'w';
  });
  if (v === 1) return stamp(base, ['mm..', 'm.m.', '.mm.'], 9, 5); // peeling
  return base;
}

/** Layered wasp paper. */
function paper(v: number): string[] {
  const base = frame((x, y) => {
    if (y < 2) return 'k';
    if (y === 15) return 'm';
    const band = (y + Math.round(Math.sin((x + y * 0.7) * 0.8) * 1.2)) % 4;
    return band === 0 ? 'L' : band === 1 ? 'W' : band === 2 ? 'W' : 'w';
  });
  if (v === 1) return stamp(base, ['.GG.', 'GggG', '.gg.'], 10, 8); // an amber drop
  return base;
}

export const WALL_PATTERNS: Readonly<Record<string, PatternFrames>> = {
  brick: WALL_SPRITE.frames,
  blocks: [blocks(0), blocks(1)],
  timber: [timber(0), timber(1)],
  panel: [panel(0), panel(1)],
  paper: [paper(0), paper(1)],
};

/** Splits 'floor/wall' (unknown names fall back to the gutter patterns). */
export function tilesetPatterns(tileset: string): { floor: PatternFrames; wall: PatternFrames; floorName: string; wallName: string } {
  const [f = 'flagstone', w = 'brick'] = tileset.split('/');
  const floorName = FLOOR_PATTERNS[f] ? f : 'flagstone';
  const wallName = WALL_PATTERNS[w] ? w : 'brick';
  return { floor: FLOOR_PATTERNS[floorName]!, wall: WALL_PATTERNS[wallName]!, floorName, wallName };
}
